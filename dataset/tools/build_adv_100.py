def main():
    base     = Path(__file__).parent.parent
    tsv_path = base / 'tsv' / 'ADV_v1.tsv'
    out_path = base / 'tsv' / 'ADV_v1.tsv'

    # 既存75行を読み込み
    existing = {}
    with open(tsv_path, encoding='utf-8-sig') as f:
        for row in csv.reader(f, delimiter='\t'):
            if len(row) < 6:
                continue
            try:
                no = int(row[0])
            except ValueError:
                continue
            existing[no] = (row[1], row[2], row[3], row[4], row[5])

    # 新規25行を追加
    for no, (et, ct, es, cs) in NEW_ROWS.items():
        existing[no] = ('ADV', et, ct, es, cs)

    # 検証
    print(f'総件数: {len(existing)}')
    missing = [n for n in range(1, 101) if n not in existing]
    if missing:
        print(f'欠落: {missing}')
        return

    # 統計確認
    err_lens = [len(v[3]) for v in existing.values()]
    cor_lens = [len(v[4]) for v in existing.values()]
    print(f'誤文 mean={statistics.mean(err_lens):.2f}, var_s={statistics.variance(err_lens):.2f}')
    print(f'正文 mean={statistics.mean(cor_lens):.2f}, var_s={statistics.variance(cor_lens):.2f}')
    print(f'誤文 min={min(err_lens)} / max={max(err_lens)}')

    # 1-100 で並び替えて保存
    with open(out_path, 'w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f, delimiter='\t')
        for new_no, orig_no in enumerate(sorted(existing.keys()), start=1):
            typ, et, ct, es, cs = existing[orig_no]
            writer.writerow([new_no, typ, et, ct, es, cs])

    print(f'保存完了: {out_path}')

if __name__ == '__main__':
    main()
